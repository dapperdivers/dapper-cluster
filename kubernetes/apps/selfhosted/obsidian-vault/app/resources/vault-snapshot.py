#!/usr/bin/env python3
"""Generate plain-Markdown views of an Obsidian vault for agents that read raw files.

Dataview queries only render inside the Obsidian app; agents reading the files see code.
This writes two notes under OUTPUT_DIR:
  - Vault Snapshot.md : today's daily note, recent dailies, recently edited and active projects
  - Vault Catalog.md  : every curated (non-generated) note grouped by folder, with its description
Files are only rewritten when their content changes (keeps Syncthing quiet), and are written
as <name>.tmp then renamed, matching the vault's .stglobalignore.

Stdlib only. Usage: vault-snapshot.py <vault-dir> [--dry-run]
"""
import datetime as dt
import os
import re
import sys
from collections import defaultdict
from zoneinfo import ZoneInfo

VAULT = sys.argv[1] if len(sys.argv) > 1 else "/vault"
DRY = "--dry-run" in sys.argv
OUTPUT_DIR = os.environ.get("OUTPUT_DIR", "Resources/Generated")
try:
    TZ = ZoneInfo(os.environ.get("TZ", "America/Chicago"))
except Exception:  # image without tzdata: fall back rather than fail the job
    print("warning: timezone data unavailable, using UTC", file=sys.stderr)
    TZ = dt.timezone.utc
SKIP_DIRS = {".obsidian", ".trash", ".stversions", ".stfolder", ".git", "Templates"}
AUTHOR = "vault-snapshot"

FM_KEY = re.compile(r"^([A-Za-z_][\w-]*):\s*(.*)$")


def parse_frontmatter(text):
    """Minimal YAML subset: top-level scalars and '- item' lists. Enough for type/status/tags."""
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---", 4)
    if end == -1:
        return {}
    data, key = {}, None
    for line in text[4:end].split("\n"):
        m = FM_KEY.match(line)
        if m:
            key, val = m.group(1), m.group(2).strip()
            if val.startswith("[") and val.endswith("]"):
                data[key] = [v.strip().strip("'\"") for v in val[1:-1].split(",") if v.strip()]
            else:
                data[key] = val.strip("'\"") if val else []
        elif key and line.lstrip().startswith("- ") and isinstance(data.get(key), list):
            data[key].append(line.lstrip()[2:].strip().strip("'\""))
    return data


def is_true(v):
    return str(v).lower() in ("true", "yes", "1")


def wikilink(rel, label=None):
    target = rel[:-3] if rel.endswith(".md") else rel
    return f"[[{target}|{label}]]" if label else f"[[{target}]]"


def load_notes():
    notes = []
    for root, dirs, files in os.walk(VAULT):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS and not d.startswith("."))
        for f in sorted(files):
            if not f.endswith(".md") or f.endswith(".excalidraw.md"):
                continue
            path = os.path.join(root, f)
            rel = os.path.relpath(path, VAULT)
            if rel.startswith(OUTPUT_DIR + os.sep):
                continue
            try:
                with open(path, encoding="utf-8") as fh:
                    head = fh.read(8192)
            except (OSError, UnicodeDecodeError):
                continue
            fm = parse_frontmatter(head)
            notes.append({
                "rel": rel,
                "name": f[:-3],
                "top": rel.split(os.sep)[0] if os.sep in rel else "(root)",
                "mtime": dt.datetime.fromtimestamp(os.path.getmtime(path), TZ),
                "type": str(fm.get("type", "")),
                "status": str(fm.get("status", "")),
                "description": str(fm.get("description", "")) if not isinstance(fm.get("description"), list) else "",
                "generated": is_true(fm.get("generated", "")),
            })
    return notes


def frontmatter(description):
    return (
        "---\n"
        f"type: index\nstatus: active\ntags:\n  - meta/generated\n"
        f"generated: true\nauthor: {AUTHOR}\n"
        f'description: "{description}"\n'
        "---\n"
    )


def build_snapshot(notes, today):
    curated = [n for n in notes if not n["generated"]]
    out = [frontmatter("Plain-Markdown dashboard for agents: today's note, recent dailies, recently edited notes and active projects. Regenerated by a cluster CronJob."),
           "# Vault Snapshot\n",
           f"> Generated {today.isoformat()} by the `{AUTHOR}` CronJob from the raw files. Do not edit; changes are overwritten.",
           "> Static stand-in for the Dataview queries in [[Home]]. Full note list: [[Vault Catalog]].\n"]

    daily_path = f"Journal/{today.year}/{today.month:02d}-{today.strftime('%B')}/{today.isoformat()}"
    exists = any(n["rel"] == daily_path + ".md" for n in notes)
    out.append("## Today\n")
    out.append(f"- {wikilink(daily_path, 'Today’s note')} ({today.strftime('%A %Y-%m-%d')}){'' if exists else ' — not created yet'}\n")

    dailies = sorted((n for n in notes if n["rel"].startswith("Journal" + os.sep) and n["type"] in ("daily", "daily-note", "journal")),
                     key=lambda n: n["name"], reverse=True)[:7]
    out.append("## Recent daily notes\n")
    out += [f"- {wikilink(n['rel'], n['name'])}" for n in dailies] or ["- (none)"]
    out.append("")

    recent = sorted((n for n in curated if not n["rel"].startswith("Journal" + os.sep)), key=lambda n: n["mtime"], reverse=True)[:20]
    out.append("## Recently edited (excluding journal and generated notes)\n")
    out.append("| Note | Edited | Description |\n|---|---|---|")
    for n in recent:
        desc = n["description"].replace("|", "\\|")
        link = wikilink(n["rel"], n["name"]).replace("|", "\\|")  # escape the alias pipe inside a table
        out.append(f"| {link} | {n['mtime'].date().isoformat()} | {desc} |")
    out.append("")

    active = [n for n in curated if n["type"] == "project" and n["status"] in ("active", "in-progress", "planning")
              and not n["rel"].startswith("Archive" + os.sep)]
    by_area = defaultdict(list)
    for n in active:
        parts = n["rel"].split(os.sep)
        by_area[os.sep.join(parts[:2]) if len(parts) > 2 else parts[0]].append(n)
    out.append("## Active projects\n")
    for area in sorted(by_area):
        out.append(f"### {area}\n")
        items = sorted(by_area[area], key=lambda n: n["mtime"], reverse=True)
        for n in items[:10]:  # most recently edited first; the catalog has the rest
            out.append(f"- {wikilink(n['rel'], n['name'])}" + (f" — {n['description']}" if n["description"] else ""))
        if len(items) > 10:
            out.append(f"- …and {len(items) - 10} more (see [[Vault Catalog]])")
        out.append("")
    if not by_area:
        out.append("- (none)\n")
    return "\n".join(out).rstrip() + "\n"


def build_catalog(notes, today):
    curated = [n for n in notes if not n["generated"]]
    gen_count = len(notes) - len(curated)
    out = [frontmatter("Catalog of every curated note in the vault grouped by folder with one-line descriptions. Read this first to find notes."),
           "# Vault Catalog\n",
           f"> Generated {today.isoformat()} by the `{AUTHOR}` CronJob. {len(curated)} curated notes listed; "
           f"{gen_count} generated notes (briefings, agent reports) omitted. See [[AGENTS]] for conventions.\n"]
    by_dir = defaultdict(list)
    for n in curated:
        by_dir[os.path.dirname(n["rel"]) or "(root)"].append(n)
    for d in sorted(by_dir, key=lambda s: (s != "(root)", s.lower())):
        out.append(f"## {d}\n")
        for n in sorted(by_dir[d], key=lambda n: n["name"].lower()):
            out.append(f"- {wikilink(n['rel'], n['name'])}" + (f" — {n['description']}" if n["description"] else ""))
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def strip_volatile(text):
    return re.sub(r"^> Generated \d{4}-\d{2}-\d{2}", "> Generated", text, flags=re.M)


def write_if_changed(rel, content):
    path = os.path.join(VAULT, rel)
    try:
        with open(path, encoding="utf-8") as fh:
            # Ignore the "Generated <date>" stamp so an unchanged catalog isn't rewritten daily.
            if strip_volatile(fh.read()) == strip_volatile(content):
                return "unchanged"
    except FileNotFoundError:
        pass
    if DRY:
        return "would write"
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(content)
    os.replace(tmp, path)
    return "written"


def main():
    if not os.path.isfile(os.path.join(VAULT, ".stfolder")) and not os.path.isdir(os.path.join(VAULT, ".stfolder")):
        # Fresh/unconfigured vault PVC (Syncthing hasn't synced it yet): skip, don't fail the job.
        print(f"warning: {VAULT} has no .stfolder marker (not synced yet?); skipping", file=sys.stderr)
        return
    today = dt.datetime.now(TZ).date()
    notes = load_notes()
    for name, content in (("Vault Snapshot.md", build_snapshot(notes, today)),
                          ("Vault Catalog.md", build_catalog(notes, today))):
        rel = os.path.join(OUTPUT_DIR, name)
        print(f"{rel}: {write_if_changed(rel, content)} ({len(content)} bytes)")
    print(f"scanned {len(notes)} notes")


if __name__ == "__main__":
    main()
